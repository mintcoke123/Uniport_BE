    static List<Map<String, Object>> classify(String text) {
        if (text == null || text.isBlank()) {
            return List.of();
        }

        List<Candidate> candidates = new ArrayList<>();
        for (GlossaryEntry entry : BEGINNER_TERMS) {
            int start = indexOfTerm(text, entry.term());
            if (start >= 0) {
                int end = start + entry.term().length();
                candidates.add(new Candidate(
                        text.substring(start, end),
                        entry.definition(),
                        entry.example(),
                        start,
                        end));
            }
        }

        candidates.sort(
                Comparator.comparingInt(Candidate::start)
                        .thenComparing((Candidate candidate) -> candidate.end() - candidate.start(), Comparator.reverseOrder())
        );

        List<Candidate> selected = new ArrayList<>();
        for (Candidate candidate : candidates) {
            if (selected.size() >= MAX_TERMS_PER_CARD) {
                break;
            }
            if (selected.stream().noneMatch(existing -> overlaps(existing, candidate))) {
                selected.add(candidate);
            }
        }

        List<Map<String, Object>> glossaryTerms = new ArrayList<>();
        for (Candidate candidate : selected) {
            Map<String, Object> item = new LinkedHashMap<>();
            item.put("term", candidate.term());
            item.put("definition", candidate.definition());
            item.put("start", candidate.start());
            item.put("end", candidate.end());
            item.put("example", candidate.example());
            glossaryTerms.add(item);
        }
        return glossaryTerms;
    }

    private static int indexOfTerm(String text, String term) {
        if (isAscii(term)) {
            String lowerText = text.toLowerCase(Locale.ROOT);
            String lowerTerm = term.toLowerCase(Locale.ROOT);
            int start = lowerText.indexOf(lowerTerm);
            while (start >= 0) {
                int end = start + term.length();
                if (hasAsciiBoundary(text, start, end)) {
                    return start;
                }
                start = lowerText.indexOf(lowerTerm, start + 1);
            }
            return -1;
        }
        return text.indexOf(term);
    }

    private static boolean hasAsciiBoundary(String text, int start, int end) {
        boolean validStart = start == 0 || !Character.isLetterOrDigit(text.charAt(start - 1));
        boolean validEnd = end == text.length() || !Character.isLetterOrDigit(text.charAt(end));
        return validStart && validEnd;
    }

    private static boolean isAscii(String term) {
        return term.chars().allMatch(value -> value < 128);
    }

    private static boolean overlaps(Candidate left, Candidate right) {
        return left.start() < right.end() && right.start() < left.end();
    }

    private static GlossaryEntry entry(String term, String definition, String example) {
        return new GlossaryEntry(term, definition, example);
    }

